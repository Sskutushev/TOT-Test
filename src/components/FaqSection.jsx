const FaqItem = ({ item, isOpen, onClick }) => {
  return (
    <div className={`faq-item ${isOpen ? 'open' : ''}`} onClick={onClick}>
      <div className="faq-question-container">
        <img src={import.meta.env.BASE_URL + 'Ellipse 110.svg'} alt="•" className="faq-icon" />
        <h3 className="faq-question">{item.question}</h3>
      </div>
      {isOpen && <p className="faq-answer">{item.answer}</p>}
    </div>
  );
};

const FaqSection = () => {
  const [openIndex, setOpenIndex] = useState(null);

  const handleItemClick = (index) => {
    setOpenIndex(openIndex === index ? null : index);
  };

  const leftColumn = faqData.slice(0, 5);
  const rightColumn = faqData.slice(5, 10);

  return (
    <section className="faq-section">
      <div className="faq-container">
        <h2 className="faq-title">Часто задаваемые вопросы</h2>
        <div className="faq-columns">
          <div className="faq-column">
            {leftColumn.map((item, index) => (
              <FaqItem 
                key={index} 
                item={item} 
                isOpen={openIndex === index}
                onClick={() => handleItemClick(index)}
              />
            ))}
          </div>
          <div className="faq-column">
            {rightColumn.map((item, index) => (
              <FaqItem 
                key={index + 5} 
                item={item} 
                isOpen={openIndex === index + 5}
                onClick={() => handleItemClick(index + 5)}
              />
            ))}
          </div>
        </div>
        <div className="faq-button-container">
            <button className="btn btn-primary">Начать сейчас</button>
        </div>
      </div>
    </section>
  );
};

export default FaqSection;